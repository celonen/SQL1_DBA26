SET PAGESIZE 1500
DESC system.results_col3;


SELECT	
	UTBILDNINGSOMRADE,
	SUN5_INRIKTNING_NAMN,
	UTBILDNINGSNAMN,
	UTBILDNINGSANORDNARE_ADMINISTR AS utbildningsanordnare,
	HUVUDMANNATYP,
	LAN,	
	KOMMUN,
	STUDIEFORM,
	BEVILJADE_UTBILDNINGSOMGANGAR AS beviljade_omgangar,
	COUNT(*) AS ansokningar,
	SUM(CASE WHEN Beslut = 'Beviljad'
		THEN 1 ELSE 0 END) AS beviljade,
	SUM(CASE WHEN Beslut = 'Avslag'
		THEN 1 ELSE 0 END) AS avslag,
	ROUND(
	100 * SUM(CASE WHEN Beslut = 'Beviljad'
		THEN 1 ELSE 0 END) / COUNT(*), 2
	) AS beviljande_procent
FROM results_col3
WHERE (UTBILDNINGSOMRADE LIKE '%Transporttj_nster%')
GROUP BY
	UTBILDNINGSOMRADE,
	SUN5_INRIKTNING_NAMN,
	UTBILDNINGSNAMN,
	UTBILDNINGSANORDNARE_ADMINISTR,
	HUVUDMANNATYP,
	LAN, 
	KOMMUN,
	STUDIEFORM,
	BEVILJADE_UTBILDNINGSOMGANGAR
ORDER BY Beviljade_utbildningsomgangar DESC, beviljande_procent DESC;


EXIT
